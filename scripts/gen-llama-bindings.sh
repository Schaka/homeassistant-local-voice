#!/usr/bin/env bash
# Regenerates src/media/{llama_sys,ggml_sys}.rs from the llama.cpp headers of
# the build in docker-bake.hcl (LLAMACPP_BUILD). Run it after each bump of
# LLAMACPP_BUILD, then `cargo test`: the generated layout checks fail at
# compile time if a struct changed in a way the code does not expect.
#
# Needs: bindgen-cli (cargo install bindgen-cli) and libclang.
set -euo pipefail
cd "$(dirname "$0")/.."
build=$(sed -n 's/^variable "LLAMACPP_BUILD" { default = "\(.*\)" }/\1/p' docker-bake.hcl)
# The headers are only read here, never committed: the library itself comes
# from the official release in the image (Dockerfile, llamacpp-stage).
dir=$(mktemp -d)
trap 'rm -rf "$dir"' EXIT
for f in include/llama.h ggml/include/ggml.h ggml/include/ggml-backend.h ggml/include/ggml-alloc.h \
         ggml/include/ggml-cpu.h ggml/include/ggml-opt.h ggml/include/gguf.h; do
    mkdir -p "$dir/$(dirname "$f")"
    curl -fsSL -o "$dir/$f" "https://raw.githubusercontent.com/ggml-org/llama.cpp/$build/$f"
done
version=$(bindgen --version | awk '{print $2}')
header="// Generated by bindgen $version from the llama.cpp $build headers.
// Regenerate with scripts/gen-llama-bindings.sh when LLAMACPP_BUILD changes.
#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, unsafe_op_in_unsafe_fn, clippy::all)]"
llama_fns='llama_(backend_init|model_default_params|context_default_params|model_load_from_file|model_free|init_from_model|free|model_get_vocab|tokenize|model_n_embd_out|batch_init|batch_free|decode|encode|get_embeddings_seq|get_memory|memory_clear|pooling_type|n_ctx|log_set|model_has_encoder|model_has_decoder)'
bindgen "$dir/include/llama.h" --dynamic-loading Llama --dynamic-link-require-all \
    --allowlist-function "$llama_fns" --no-doc-comments --use-core --merge-extern-blocks \
    --raw-line "$header" -o src/media/llama_sys.rs -- -I"$dir/include" -I"$dir/ggml/include"
bindgen "$dir/ggml/include/ggml-backend.h" --dynamic-loading Ggml --dynamic-link-require-all \
    --allowlist-function 'ggml_backend_(load|dev_count|dev_get|dev_type|dev_name)' --no-doc-comments --use-core \
    --raw-line "$header" -o src/media/ggml_sys.rs -- -I"$dir/ggml/include"
echo "bindings for llama.cpp $build written"
